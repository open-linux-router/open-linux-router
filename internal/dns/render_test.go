func testBackend(t *testing.T) Backend {
	t.Helper()
	return NewBackend(RootedPaths(t.TempDir())).WithSource("/etc/open-linux-router/olr.json")
}

func renderOne(t *testing.T, b Backend, c Config, path string) string {
	t.Helper()
	out, err := b.Render(c, testLinks())
	if err != nil {
		t.Fatalf("Render: %v", err)
	}
	f, ok := out.Get(path)
	if !ok {
		t.Fatalf("nothing rendered at %s; got %v", path, out.Paths())
	}
	return string(f.Data)
}

// renderDirectives is the rendered file reduced to what the daemon actually
// reads — comments and blank lines gone.
//
// Assertions about behaviour belong against this rather than against the raw
// file. Roughly half of what we render is prose explaining the directive below
// it, so a test looking for "forward-zone" or "reject" in the raw bytes matches
// the sentence saying why we do not use one.
func renderDirectives(t *testing.T, b Backend, c Config, path string) string {
	t.Helper()
	return string(b.Canonical([]byte(renderOne(t, b, c, path))))
}

// Drift detection compares rendered bytes against what is on disk, so a
// renderer that is not a pure function of its inputs would make every box look
// permanently drifted.
func TestRenderIsDeterministic(t *testing.T) {
	b := testBackend(t)
	cfg := validConfig()
	cfg.Policies = []Policy{
		{Name: "kids", Clients: []netip.Prefix{netip.MustParsePrefix("192.168.1.50/32")},
			Block: []string{"b.example", "a.example"}},
		{Name: "default", Block: []string{"ads.example"}},
	}
	cfg.Hijack = Hijack{Enabled: true, Interfaces: []string{"lan0"}, BlockDoT: true}

	first, err := b.Render(cfg, testLinks())
	if err != nil {
		t.Fatal(err)
	}
	second, err := b.Render(cfg, testLinks())
	if err != nil {
		t.Fatal(err)
	}

	if len(first.Files) != len(second.Files) {
		t.Fatalf("file count differs: %d vs %d", len(first.Files), len(second.Files))
	}
	for i := range first.Files {
		if first.Files[i].Path != second.Files[i].Path {
			t.Errorf("file %d: path %s vs %s", i, first.Files[i].Path, second.Files[i].Path)
		}
		if string(first.Files[i].Data) != string(second.Files[i].Data) {
			t.Errorf("%s rendered differently on a second call", first.Files[i].Path)
		}
	}
}

// Every generated file carries an ownership header naming the file that
// produced it (design.md §7). JSON has no comments, so relay.json and the
// policy files are the documented exception.
func TestRenderedFilesCarryAnOwnershipHeader(t *testing.T) {
	b := testBackend(t)
	cfg := validConfig()
	cfg.Hijack = Hijack{Enabled: true, Interfaces: []string{"lan0"}}

	out, err := b.Render(cfg, testLinks())
	if err != nil {
		t.Fatal(err)
	}
	for _, f := range out.Files {
		if strings.HasSuffix(f.Path, ".json") {
			continue
		}
		body := string(f.Data)
		if !strings.Contains(body, "Generated by open-linux-router") {
			t.Errorf("%s has no ownership header", f.Path)
		}
		if !strings.Contains(body, "/etc/open-linux-router/olr.json") {
			t.Errorf("%s does not name the file that produced it", f.Path)
		}
	}
}

func TestRenderUnbound(t *testing.T) {
	b := testBackend(t)
	conf := renderDirectives(t, b, validConfig(), b.Paths.UnboundConf)

	// unbound must be unreachable from the network by construction, not by
	// firewall rule: the relay owns :53 and this sits behind it on loopback.
	for _, want := range []string{
		"interface: 127.0.0.1@5353",
		"access-control: 0.0.0.0/0 refuse",
		"access-control: 127.0.0.0/8 allow",
	} {
		if !strings.Contains(conf, want) {
			t.Errorf("unbound.conf is missing %q:\n%s", want, conf)
		}
	}
	if strings.Contains(conf, "interface: 0.0.0.0") {
		t.Error("unbound was told to listen on the wildcard")
	}
}

// The one range deliberately absent from the rebinding list.
//
// olr does not route by domain name and so has no use for a fake IP of its own
// (docs/gateway.md §4). This guards somebody else's setup: an operator running
// mihomo in fake-IP mode with `upstream` pointed at its resolver would have
// every answer stripped, with the cause a line in a rendered config they have
// no reason to suspect.
func TestRenderDoesNotStripTheBenchmarkingRange(t *testing.T) {
	b := testBackend(t)
	conf := renderDirectives(t, b, validConfig(), b.Paths.UnboundConf)

	if !strings.Contains(conf, "private-address: 192.168.0.0/16") {
		t.Error("rebinding protection is not configured at all")
	}
	if strings.Contains(conf, "198.18.") {
		t.Error("198.18.0.0/15 is in the rebinding list; that silently breaks a fake-IP proxy behind us")
	}
}

func TestRenderForwarding(t *testing.T) {
	b := testBackend(t)

	t.Run("recursing renders no forward zone", func(t *testing.T) {
		conf := renderDirectives(t, b, validConfig(), b.Paths.UnboundConf)
		if strings.Contains(conf, "forward-zone") {
			t.Errorf("a forward-zone was rendered in recursing mode:\n%s", conf)
		}
	})

	t.Run("plaintext", func(t *testing.T) {
		cfg := validConfig()
		cfg.Upstream = Upstream{Mode: ModeForward, Servers: []netip.AddrPort{
			netip.AddrPortFrom(netip.MustParseAddr("1.1.1.1"), 0),
		}}
		conf := renderDirectives(t, b, cfg, b.Paths.UnboundConf)
		if !strings.Contains(conf, "forward-addr: 1.1.1.1@53") {
			t.Errorf("a portless forwarder did not default to 53:\n%s", conf)
		}
	})

	t.Run("DoT defaults to 853 and pins the name", func(t *testing.T) {
		// The difference between "1.1.1.1 with tls on" working and silently
		// trying DoT against plaintext 53.
		cfg := validConfig()
		cfg.Upstream = Upstream{
			Mode:    ModeForward,
			Servers: []netip.AddrPort{netip.AddrPortFrom(netip.MustParseAddr("1.1.1.1"), 0)},
			TLS:     true,
			TLSName: "cloudflare-dns.com",
		}
		conf := renderDirectives(t, b, cfg, b.Paths.UnboundConf)
		if !strings.Contains(conf, "forward-tls-upstream: yes") {
			t.Error("TLS was not enabled on the forward zone")
		}
		if !strings.Contains(conf, "forward-addr: 1.1.1.1@853#cloudflare-dns.com") {
			t.Errorf("the forwarder was not rendered with the DoT port and name:\n%s", conf)
		}
	})
}

func TestRenderRelayDerivesAllowFromTheListenNetworks(t *testing.T) {
	b := testBackend(t)
	cfg := validConfig()
	cfg.AllowFrom = nil

	relay := renderOne(t, b, cfg, b.Paths.RelayConf)
	if !strings.Contains(relay, "192.168.1.0/24") {
		t.Errorf("an empty allow_from did not derive the listen network:\n%s", relay)
	}
	// Never open. An empty list denies everybody in the relay, and deriving is
	// the only reading that cannot accidentally ship an amplifier.
	if strings.Contains(relay, "0.0.0.0/0") {
		t.Error("the derived access list is open")
	}
}

