// Policies live in a directory because the relay re-reads it on SIGHUP. That is
// what makes editing a blocklist — much the most common change — free.
func TestRenderPoliciesAreReloadable(t *testing.T) {
	b := testBackend(t)
	cfg := validConfig()
	cfg.Policies = []Policy{{Name: "kids", Block: []string{"example.com"}}}

	out, err := b.Render(cfg, testLinks())
	if err != nil {
		t.Fatal(err)
	}

	path := filepath.Join(b.Paths.PolicyDir, "kids.json")
	f, ok := out.Get(path)
	if !ok {
		t.Fatalf("no policy file at %s; got %v", path, out.Paths())
	}
	if !f.Reloadable {
		t.Error("a policy file is not marked reloadable, so editing a blocklist would restart DNS")
	}
	if f.Unit != b.RelayUnit() {
		t.Errorf("policy file belongs to %q, want %q", f.Unit, b.RelayUnit())
	}
	if !strings.Contains(string(f.Data), "example.com") {
		t.Errorf("the blocked name is not in the rendered policy:\n%s", f.Data)
	}
	// The default response has to be explicit in the file: the relay must not
	// have to know what an empty string means here.
	if !strings.Contains(string(f.Data), string(RespondNXDOMAIN)) {
		t.Errorf("the policy did not render a response:\n%s", f.Data)
	}
}

// Nothing about the resolver's own configuration changes when a blocklist does,
// so a policy edit must not touch unbound's file at all.
func TestRenderSeparatesTheTwoBackends(t *testing.T) {
	b := testBackend(t)

	before := renderOne(t, b, validConfig(), b.Paths.UnboundConf)

	cfg := validConfig()
	cfg.Policies = []Policy{{Name: "kids", Block: []string{"example.com"}}}
	after := renderOne(t, b, cfg, b.Paths.UnboundConf)

	if before != after {
		t.Error("adding a blocklist changed unbound's configuration, which would restart the resolver")
	}
}

func TestRenderHijack(t *testing.T) {
	b := testBackend(t)
	cfg := validConfig()
	cfg.Listen = append(cfg.Listen, netip.MustParseAddrPort("[fd00::1]:53"))
	cfg.AllowFrom = append(cfg.AllowFrom, netip.MustParsePrefix("fd00::/64"))
	cfg.Hijack = Hijack{Enabled: true, Interfaces: []string{"lan0"}, BlockDoT: true}
	cfg.Normalize()

	nft := renderDirectives(t, b, cfg, b.Paths.HijackNFT)

	// The idempotent flush-and-recreate form: nft refuses to delete a table
	// that is not there, and this file has to survive being loaded twice.
	if !strings.Contains(nft, "table inet olr-dns\ndelete table inet olr-dns") {
		t.Errorf("the ruleset is not idempotent:\n%s", nft)
	}
	for _, want := range []string{
		`iifname { "lan0" } ip daddr != 192.168.1.1 udp dport 53 dnat ip to 192.168.1.1:53`,
		`iifname { "lan0" } ip daddr != 192.168.1.1 tcp dport 53 dnat ip to 192.168.1.1:53`,
		`dnat ip6 to [fd00::1]:53`,
		"tcp dport 853 drop",
		"udp dport 853 drop",
	} {
		if !strings.Contains(nft, want) {
			t.Errorf("the ruleset is missing %q:\n%s", want, nft)
		}
	}
	// A reject tells the client to fall back immediately; the whole point is
	// that it does not.
	if strings.Contains(nft, "reject") {
		t.Error("DoT is rejected rather than dropped, which makes falling back instant")
	}
}

