// Roughly half of what we render is explanation. Without normalisation,
// rewording a comment in a new olr release would mark every deployed box as
// drifted and restart its resolver.
func TestCanonicalIgnoresComments(t *testing.T) {
	b := testBackend(t)
	withComments := []byte("# one explanation\nserver:\n\n  # another\n  verbosity: 0\n")
	reworded := []byte("# a better explanation\nserver:\n  verbosity: 0\n")

	if string(b.Canonical(withComments)) != string(b.Canonical(reworded)) {
		t.Errorf("rewording a comment changed the canonical form:\n%q\n%q",
			b.Canonical(withComments), b.Canonical(reworded))
	}
	if string(b.Canonical(withComments)) == string(b.Canonical([]byte("server:\n  verbosity: 1\n"))) {
		t.Error("a real change was normalised away")
	}
}

func TestUnitForClassifiesStrayFiles(t *testing.T) {
	b := testBackend(t)
	tests := map[string]string{
		b.Paths.UnboundConf: b.ResolverUnit(),
		b.Paths.RelayConf:   b.RelayUnit(),
		b.Paths.HijackNFT:   b.RelayUnit(),
		filepath.Join(b.Paths.PolicyDir, "stale.json"): b.RelayUnit(),
		"/etc/somewhere/else":                          "",
	}
	for path, want := range tests {
		if got := b.unitFor(path); got != want {
			t.Errorf("unitFor(%s) = %q, want %q", path, got, want)
		}
	}
}
