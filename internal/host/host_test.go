// Debian 13's /etc/dhcpcd.conf as shipped, abridged — including an `interface`
// block of the operator's own, which is what makes the file positional.
const stockDhcpcd = `# A sample configuration for dhcpcd.
hostname
duid
persistent
vendorclassid
option domain_name_servers, domain_name, domain_search
require dhcp_server_identifier
slaac private

interface eth9
	static ip_address=10.0.0.2/24
`

const dhcpcdResolv = `# Generated by dhcpcd
search home.arpa
# /etc/resolv.conf.head can replace this line
nameserver 10.9.9.9
options edns0
# /etc/resolv.conf.tail can replace this line
`

var uplinkDNS = []netip.Addr{netip.MustParseAddr("192.168.1.1")}

func TestDhcpcdBlocksRoundTrip(t *testing.T) {
	d := Desired{IPv4: []string{"ens18", "ens19", "ens18"}, Resolvers: uplinkDNS}
	got := renderDhcpcd(stockDhcpcd, d)

	if !strings.HasPrefix(got, blockBegin) || !strings.Contains(got[:200], "nohook resolv.conf") {
		t.Errorf("the global option is not at the top, where it applies to every interface:\n%s", got)
	}
	tail := got[strings.LastIndex(got, blockBegin):]
	if !strings.Contains(tail, "interface ens18\n\tipv6only\ninterface ens19\n\tipv6only\n") {
		t.Errorf("the interface block is wrong or not last:\n%s", tail)
	}
	if again := renderDhcpcd(got, d); again != got {
		t.Errorf("rendering twice changed the file:\n%s", again)
	}
	if back := renderDhcpcd(got, Desired{}); back != stockDhcpcd {
		t.Errorf("giving back did not restore the file exactly:\n%q\nwant\n%q", back, stockDhcpcd)
	}
	if same := renderDhcpcd(stockDhcpcd, Desired{}); same != stockDhcpcd {
		t.Error("a file olr never touched was changed")
	}
}

